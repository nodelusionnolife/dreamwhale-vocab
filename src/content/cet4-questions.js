const pad3 = (number) => String(number).padStart(3, '0');

function rotateOptions(answer, distractors, index) {
  const options = [answer, ...distractors];
  const offset = index % options.length;
  return [...options.slice(offset), ...options.slice(0, offset)];
}

function derivedQuestions(seed, index) {
  const [answer, topic, difficulty, stem, distractors] = seed;
  const entry = ENTRY_BY_WORD.get(answer);
  const variantGroup = `c4v-${pad3(index + 1)}`;
  return [
    {
      id: `c4c-${pad3(index + 21)}`,
      type: 'choice',
      difficulty,
      topic,
      stem,
      options: rotateOptions(answer, distractors, index),
      answer,
      explanation: `${answer}：${entry?.m || ''}`,
      targetWords: [answer],
      variantGroup,
    },
    {
      id: `c4f-${pad3(index + 11)}`,
      type: 'fill',
      difficulty,
      topic,
      stem: stem.replace('___', '______'),
      answer,
      accepts: [answer],
      hint: `${entry?.p || ''} ${entry?.m || ''}`.trim(),
      explanation: `${answer}：${entry?.m || ''}`,
      targetWords: [answer],
      variantGroup,
    },
  ];
}


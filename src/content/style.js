/* ---------------- 中文写作规范 ---------------- */

export const WRITING_RULES = `<中文写作规范>
- 使用左分支结构：修饰集中在中心词之前，或把分句提前。
  例：「他的笑容实在冷淡，像是事不关己一样。」→「他事不关己地冷笑着。」
- 比喻必须以左分支结构出现，或干脆略去比喻；禁止右分支的分句比喻。
- 比喻词不要只用「像」，可用「如同」「仿佛」「好似」「看起来是」，或用暗喻、隐喻省掉比喻词。
- 状态补语略去或前置。例：「她速度快得不像人类」→「她速度极快」。
- 杜绝欧化句式与长串定语从句。
- 禁止以比喻去描写角色的语气、声音、腔调、眼神、视线（成语除外）。
- 禁止「她/他自己」式的冗余定语。例：「带着连她自己都没意识到的期待」→「带着些许期待」。
- 对白独立成段，不加「他说」「某某说」这类提示语。
</中文写作规范>`;


/* ---------------- 自攻击 ---------------- */

/**
 * 自攻击块：把「你在这一步最容易犯的错」逐条点名。
 * 比笼统要求「注意质量」有效得多——它把模型自己的失败模式摆到台面上。
 */
export function selfAttack(errors) {
  return `<你最易犯的错误>
以下是你在这个任务上反复出现的失误，逐条避免：
${errors.map((e, i) => `${i + 1}. ${e}`).join('\n')}
</你最易犯的错误>`;
}

/* ---------------- 禁词块生成器 ---------------- */

export function bannedBlock() {
  return `【反八股：以下词与句式一律不得出现】
${BANNED_PHRASES.map((x) => `- ${x}`).join('\n')}

【以下结构属于滥用】
${BANNED_PATTERNS.map((x) => `- ${x}`).join('\n')}`;
}

